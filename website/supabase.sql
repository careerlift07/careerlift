-- SUPABASE STORAGE: RESOURCE FILE UPLOADS
-- =========================================================
-- Creates a public bucket named "resources" for PDFs and images.
-- The admin portal uploads directly into this bucket.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'resources',
  'resources',
  true,
  20971520,
  array['application/pdf','image/jpeg','image/png','image/webp']
)
on conflict (id) do update
set public = true,
    file_size_limit = 20971520,
    allowed_mime_types = array['application/pdf','image/jpeg','image/png','image/webp'];

-- Anyone can view files because the bucket is public.
drop policy if exists "Public can view resource files" on storage.objects;
create policy "Public can view resource files"
on storage.objects for select
to public
using (bucket_id = 'resources');

-- Only CAREERLIFT admins can upload files.
drop policy if exists "Admins can upload resource files" on storage.objects;
create policy "Admins can upload resource files"
on storage.objects for insert
to authenticated
with check (bucket_id = 'resources' and public.is_admin());

-- Only CAREERLIFT admins can delete files.
drop policy if exists "Admins can delete resource files" on storage.objects;
create policy "Admins can delete resource files"
on storage.objects for delete
to authenticated
using (bucket_id = 'resources' and public.is_admin());

