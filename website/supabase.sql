-- PUBLIC CONTACT PROFILE
create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  phone text,
  email text,
  telegram_url text,
  whatsapp_url text,
  is_active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.contacts enable row level security;

drop policy if exists "Public can read active contacts" on public.contacts;
create policy "Public can read active contacts" on public.contacts for select to anon, authenticated using (is_active = true or public.is_admin());

drop policy if exists "Admins can insert contacts" on public.contacts;
create policy "Admins can insert contacts" on public.contacts for insert to authenticated with check (public.is_admin() and created_by = auth.uid());

